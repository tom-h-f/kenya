def test_incumbent_replay_reproduces_the_live_selectors_picks(corpus, ground_truth):
    """The gate on the whole module. The expected lists come from running
    `kenya_monitor.runner.hot_objects` over this same corpus."""
    con, _root, manifest = corpus
    times = [datetime.fromisoformat(t) for t in ground_truth["pass_times"]]
    policy = replay.IncumbentCensus(**{
        k: ground_truth["params"][k]
        for k in ("band_min", "band_max", "lookback_days", "top_retweeted", "refresh_hours",
                  "retweeters_limit")
    })
    result = replay.replay(
        con, policy=policy, manifest=manifest, times=times, snapshot="fixture", seed=False
    )
    got = [list(step.targets) for step in result.steps]
    assert got == ground_truth["selected"]


def test_reproduction_recall_and_precision_are_exact_on_the_fixture(corpus, ground_truth):
    con, _root, manifest = corpus
    # Pass k's selection is censused a minute later, so replay one minute before
    # each recorded engagement write - the moment the pass began.
    times = [datetime.fromisoformat(t) for t in ground_truth["pass_times"]]
    policy = replay.IncumbentCensus(
        band_min=3, band_max=100, lookback_days=2, top_retweeted=5, refresh_hours=12
    )
    rep = replay.reproduce(
        con, manifest=manifest, times=times, snapshot="fixture", policy=policy
    )
    assert rep.recall == 1.0
    assert rep.precision == 1.0
    assert rep.jaccard == 1.0
    assert rep.per_pass["observed_only"].sum() == 0


def test_reproduction_carries_the_snapshot_and_the_limitation(corpus, ground_truth):
    con, _root, manifest = corpus
    times = [datetime.fromisoformat(t) for t in ground_truth["pass_times"]]
    rep = replay.reproduce(
        con,
        manifest=manifest,
        times=times,
        snapshot="2026-09-05-promotion-off",
        policy=replay.IncumbentCensus(top_retweeted=5),
    )
    assert rep.snapshot == "2026-09-05-promotion-off"
    assert "incumbent policy" in rep.limitation


def test_a_leaking_replay_would_have_been_caught(corpus, ground_truth):
    """The reproduction check earns its keep only if it can fail. A policy given
    the whole corpus at every step selects objects that did not exist yet, and
    the recorded ground truth rejects it."""
    con, _root, manifest = corpus
    times = [datetime.fromisoformat(t) for t in ground_truth["pass_times"]]
    end = max(times) + timedelta(days=1)
    leaky = [end, end, end]
    result = replay.replay(
        con,
        policy=replay.IncumbentCensus(top_retweeted=5),
        manifest=manifest,
        times=leaky,
        snapshot="fixture",
        seed=False,
    )
    assert [list(s.targets) for s in result.steps] != ground_truth["selected"]
    # o17 arrives in the third collection batch and cannot be selectable first.
    assert "o17" in result.steps[0].targets


