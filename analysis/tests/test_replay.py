"""The replay harness has one correctness property: a policy cannot see the future.

Everything else it does is bookkeeping. So these tests spend most of their
effort on the two ways a policy could see past *t* - reading an object written
later, and naming a target it had no way to know - and on the acceptance check
that the replayed incumbent reproduces what the live selector actually picked.

That ground truth comes from `fixtures/replay/`, generated by running
`kenya_monitor.runner.hot_objects` itself; see the generator's docstring for why
a port cannot be validated against itself. Everything here is offline: a git
worktree has no R2 credentials, and a local directory stands in for the bucket.
"""

from __future__ import annotations

import json
import shutil
from datetime import datetime, timedelta, timezone
from pathlib import Path

import duckdb
import pandas as pd
import pytest

from kma import bench, replay

UTC = timezone.utc
FIXTURES = Path(__file__).resolve().parent / "fixtures" / "replay"


class LocalR2:
    """`list_objects_v2` over a local directory. Unpaginated - `test_bench.py`
    already covers the pagination path, and this suite is about time, not keys."""

    def __init__(self, root: Path) -> None:
        self.root = root

    def list_objects_v2(self, Bucket: str, Prefix: str, ContinuationToken: str | None = None):
        keys = sorted(
            str(p.relative_to(self.root))
            for p in self.root.rglob("*")
            if p.is_file() and str(p.relative_to(self.root)).startswith(Prefix)
        )
        return {
            "Contents": [
                {"Key": k, "Size": (self.root / k).stat().st_size, "ETag": f'"etag-{k}"'}
                for k in keys
            ],
            "IsTruncated": False,
        }


def _manifest(con: duckdb.DuckDBPyConnection, root: Path) -> pd.DataFrame:
    return bench.snapshot(
        "fixture",
        prefixes=("posts", "engagements"),
        con=con,
        client=LocalR2(root),
        uri=lambda key: f"{root}/{key}",
        write=False,
    )


@pytest.fixture
def ground_truth() -> dict:
    return json.loads((FIXTURES / "ground_truth.json").read_text())


@pytest.fixture
def corpus(tmp_path) -> tuple[duckdb.DuckDBPyConnection, Path, pd.DataFrame]:
    """The checked-in corpus, materialised into a local stand-in for the bucket.

    It is checked in as CSV because the repo gitignores `*.parquet` wholesale,
    and that rule exists so corpus extracts cannot be committed by accident -
    weakening it for test data is the wrong trade. The harness pins parquet
    objects by path, so the CSVs are converted here rather than read directly:
    `run=...parquet.csv` -> `run=...parquet`, keeping the hive layout and the
    write timestamps that dating an object depends on.
    """
    root = tmp_path / "bucket"
    con = duckdb.connect()
    for csv in sorted((FIXTURES / "corpus").rglob("*.csv")):
        target = root / csv.relative_to(FIXTURES / "corpus").with_suffix("")
        target.parent.mkdir(parents=True, exist_ok=True)
        con.execute(
            f"COPY (SELECT * FROM read_csv('{csv}', header=true)) "
            f"TO '{target}' (FORMAT parquet)"
        )
    return con, root, _manifest(con, root)


def _write_posts(con: duckdb.DuckDBPyConnection, root: Path, when: datetime, rows: list[dict]):
    """Post rows into a run object keyed by `when`, as the collector writes them."""
    frame = pd.DataFrame(rows)
    key = (
        f"posts/platform=x/type=search/dt={when:%Y-%m-%d}"
        f"/run={when:%Y%m%dT%H%M%SZ}.parquet"
    )
    path = root / key
    path.parent.mkdir(parents=True, exist_ok=True)
    con.register("_t", frame)
    con.execute(f"COPY _t TO '{path}' (FORMAT parquet)")
    con.unregister("_t")


def _write_engagements(
    con: duckdb.DuckDBPyConnection, root: Path, when: datetime, rows: list[dict]
) -> None:
    key = f"engagements/platform=x/dt={when:%Y-%m-%d}/run={when:%Y%m%dT%H%M%SZ}.parquet"
    path = root / key
    path.parent.mkdir(parents=True, exist_ok=True)
    con.register("_e", pd.DataFrame(rows))
    con.execute(f"COPY _e TO '{path}' (FORMAT parquet)")
    con.unregister("_e")


def _post(pid: str, oid: str, degree: int, author: str, created: datetime, collected: datetime):
    return {
        "platform": "x",
        "platform_post_id": pid,
        "author_id": author,
        "created_at": created,
        "is_repost": True,
        "repost_of_id": oid,
        "repost_count": degree,
        "reply_count": 0,
        "quote_count": 0,
        "quoted_post_id": None,
        "in_reply_to_id": None,
        "conversation_id": oid,
        "collected_at": collected,
    }


