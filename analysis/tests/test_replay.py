def test_score_counts_fused_edges_per_request(corpus, ground_truth):
    con, _root, manifest = corpus
    times = [datetime.fromisoformat(t) for t in ground_truth["pass_times"]]
    result = replay.replay(
        con, policy=replay.IncumbentCensus(top_retweeted=5), manifest=manifest,
        times=times, snapshot="fixture", seed=False,
    )
    got = replay.score(con, manifest, result)
    assert got.edges > 0
    assert got.users > 0
    assert got.planned_requests == result.planned_requests
    assert got.edges_per_request == pytest.approx(got.edges / got.planned_requests)


def test_score_prices_the_realised_fetch_from_the_incidence_that_came_back(corpus, ground_truth):
    con, _root, manifest = corpus
    t = datetime.fromisoformat(ground_truth["pass_times"][0])
    result = replay.replay(
        con, policy=replay.IncumbentCensus(top_retweeted=5), manifest=manifest,
        times=[t], snapshot="fixture", seed=False,
    )
    got = replay.score(con, manifest, result)
    # Planned cost is priced off `repost_count`, a platform counter; realised
    # cost is priced off the DISTINCT accounts that came back. The fixture draws
    # amplifiers from a pool of 60, so its denser objects return fewer accounts
    # than their counter claims - which is the same direction real data
    # diverges, and the reason both numbers are reported instead of one.
    assert 0 < got.realised_requests < got.planned_requests
    assert got.edges_per_realised_request > got.edges_per_request


def test_score_reports_requests_it_cannot_score(corpus, ground_truth):
    """The incumbent-bias statement, as a number. An object the census never
    covered has no incidence in the corpus, so the harness can only return zero
    for it - and says so rather than folding it into the denominator silently."""
    con, _root, manifest = corpus
    t = datetime.fromisoformat(ground_truth["pass_times"][0])
    cand = replay.replay(
        con, policy=replay.UnbandedCensus(top_retweeted=50), manifest=manifest,
        times=[t], snapshot="fixture", seed=False,
    )
    got = replay.score(con, manifest, cand)
    assert got.unscorable_targets > 0
    assert 0.0 < got.unscorable_share < 1.0
    assert got.as_row()["limitation"] == replay.LIMITATION


def test_score_applies_the_v2_activity_floor(corpus):
    """A user acting on one entity cannot express coordination: two users whose
    only action is the same object have identical one-hot TF-IDF vectors, so
    their cosine is 1.0 whatever IDF does (`coord2.MIN_ENTITIES_PER_USER`). A
    policy that buys nothing but such users has bought no edges, and the metric
    must not credit it with a clique."""
    con, root, _m = corpus
    when = datetime(2026, 9, 2, 12, 0, tzinfo=UTC)
    _write_engagements(
        con,
        root,
        when,
        [
            {
                "platform": "x",
                "platform_post_id": "single",
                "platform_user_id": f"once-{i}",
                "kind": "retweet",
                "collected_at": when,
            }
            for i in range(3)
        ],
    )
    manifest = _manifest(con, root)
    result = replay.ReplayResult(
        snapshot="fixture",
        policy="hand-built",
        params={},
        steps=[
            replay.StepRecord(
                t=when, requested=1, requests=1, targets=("single",), degrees=(1,)
            )
        ],
    )
    assert replay.score(con, manifest, result, min_entities=2).edges == 0
    assert replay.score(con, manifest, result, min_entities=1).edges == 3


