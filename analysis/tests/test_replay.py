def test_the_ledger_is_seeded_from_corpus_history_before_the_window(corpus, ground_truth):
    """A replay starting mid-history inherits a census. Without the seed the
    policy re-fetches completed work and inflates its request count and its
    yield together."""
    con, _root, manifest = corpus
    third = datetime.fromisoformat(ground_truth["pass_times"][2])
    seeded = replay.replay(
        con, policy=replay.IncumbentCensus(top_retweeted=5), manifest=manifest,
        times=[third], snapshot="f", seed=True,
    )
    cold = replay.replay(
        con, policy=replay.IncumbentCensus(top_retweeted=5), manifest=manifest,
        times=[third], snapshot="f", seed=False,
    )
    already = {oid for pass_ids in ground_truth["selected"][:2] for oid in pass_ids}
    assert not set(seeded.targets) & already
    assert set(cold.targets) & already


