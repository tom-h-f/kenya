def test_clipped_source_excludes_objects_written_after_t(corpus):
    con, _root, manifest = corpus
    early = replay.clipped_source(manifest, "posts", datetime(2026, 9, 1, 0, 0, tzinfo=UTC))
    late = replay.clipped_source(manifest, "posts", datetime(2026, 9, 2, tzinfo=UTC))
    assert early.count("run=") == 1
    assert late.count("run=") == 3
    assert con.sql(f"SELECT count(*) FROM {early}").fetchone()[0] < con.sql(
        f"SELECT count(*) FROM {late}"
    ).fetchone()[0]


def test_clipped_source_also_clips_rows_inside_an_admitted_object(corpus):
    """Object-level pinning is not enough: the collector flushes mid-pass, so a
    single object can hold rows from both sides of `t`."""
    con, root, _m = corpus
    written = datetime(2026, 9, 3, 12, 0, tzinfo=UTC)
    created = datetime(2026, 9, 3, 6, 0, tzinfo=UTC)
    _write_posts(
        con,
        root,
        written,
        [
            _post("straddle-early", "sx", 9, "a1", created, written - timedelta(minutes=20)),
            _post("straddle-late", "sx", 9, "a2", created, written + timedelta(minutes=20)),
        ],
    )
    manifest = _manifest(con, root)
    mid = written + timedelta(minutes=1)
    src = replay.clipped_source(manifest, "posts", mid)
    ids = {r[0] for r in con.sql(f"SELECT platform_post_id FROM {src}").fetchall()}
    assert "straddle-early" in ids
    assert "straddle-late" not in ids


def test_clipped_source_is_none_when_nothing_predates_t(corpus):
    _con, _root, manifest = corpus
    assert replay.clipped_source(manifest, "posts", datetime(2020, 1, 1, tzinfo=UTC)) is None


def test_clipped_source_drops_objects_whose_write_time_is_unreadable(corpus):
    """An object that cannot be dated cannot be proven to predate `t`, so it is
    excluded. Admitting it is how leakage gets in."""
    con, root, _m = corpus
    stray = root / "posts/platform=x/type=search/dt=2026-09-01/undated.parquet"
    shutil.copy(next((root / "posts").rglob("*.parquet")), stray)
    manifest = _manifest(con, root)
    src = replay.clipped_source(manifest, "posts", datetime(2026, 9, 9, tzinfo=UTC))
    assert "undated.parquet" not in src


